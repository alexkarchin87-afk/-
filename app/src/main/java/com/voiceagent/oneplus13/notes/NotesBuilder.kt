package com.voiceagent.oneplus13.notes

import com.voiceagent.oneplus13.core.LLMClient

/**
 * "Конспекты-конструкторы": собирает один конспект из разных источников (текст
 * с диктофона/лекции, текст со слайдов PPTX, текст/описания страниц PDF или
 * фото учебника) и умеет дополнять уже готовый конспект новым куском, не
 * переписывая всё заново.
 *
 * Схемы/изображения: если среди источников есть строка вида
 * "Изображение схемы: [scheme_1.jpg — строение чёрной дыры]" (её формирует
 * вызывающий код на основе прикреплённого пользователем файла), модель обязана
 * вставить `![Строение чёрной дыры](scheme_1.jpg)` в подходящее по смыслу место.
 */
class NotesBuilder(private val llm: LLMClient) {

    private val formattingRules = """
        Правила оформления конспекта:
        1. Заголовок темы — ЗАГЛАВНЫМИ БУКВАМИ через `#`.
        2. Строгая иерархия: этап (1., 2., 3. …) -> подпункт (1), 2) …) -> маркер (•).
        3. После каждого пункта — краткое пояснение/расшифровка термина/пример в
           круглых скобках, например: "Гравитация — (сила притяжения между телами)".
        4. Если среди источников есть строка "Изображение схемы: [имя_файла —
           описание]", вставь `![описание](имя_файла)` строго в то место
           конспекта, где она логически нужна — не в конец списком.
        5. Пиши по-русски, без лишних вступлений и заключений — только сам конспект.
    """.trimIndent()

    /** Собрать новый конспект с нуля из одного или нескольких источников. */
    suspend fun build(topic: String, sources: List<String>): String {
        val prompt = "Ты помогаешь собрать школьный конспект из нескольких источников.\n$formattingRules"
        val userText = "Тема: $topic\n\nИсточники (объедини их в один связный конспект):\n" +
            sources.mapIndexed { i, s -> "--- Источник ${i + 1} ---\n$s" }.joinToString("\n\n")
        return llm.complete(prompt, emptyList(), userText)
    }

    /** Дополнить уже существующий конспект новым куском (например, услышанными
     *  словами учителя), сохраняя структуру и стиль, не переписывая всё с нуля. */
    suspend fun extend(existingMarkdown: String, addition: String): String {
        val prompt = """
            Тебе дан готовый конспект и новый кусок информации для добавления.
            Найди в конспекте подходящее по смыслу место и аккуратно впиши туда
            новую информацию с сохранением того же стиля (нумерация, пояснения в
            скобках), НЕ переписывая и не пересказывая заново то, что уже есть.
            Верни ПОЛНЫЙ обновлённый конспект целиком.
            $formattingRules
        """.trimIndent()
        val userText = "Текущий конспект:\n$existingMarkdown\n\nДобавить: $addition"
        return llm.complete(prompt, emptyList(), userText)
    }
}
